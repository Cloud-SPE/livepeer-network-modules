// Command manifest-doc regenerates the illustrative protocol envelope document.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"

	"github.com/Cloud-SPE/livepeer-network-modules/service-registry-daemon/internal/types"
)

func main() {
	check := flag.Bool("check", false, "fail if the generated document is stale")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	const source = "../livepeer-network-protocol/manifest/examples/minimal.json"
	const target = "docs/generated/manifest-example.md"
	raw, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	if _, err := types.DecodeCoordinatorEnvelope(raw); err != nil {
		return fmt.Errorf("protocol example does not decode: %w", err)
	}
	var pretty bytes.Buffer
	if err := json.Indent(&pretty, bytes.TrimSpace(raw), "", "  "); err != nil {
		return err
	}
	body := []byte("# Manifest example\n\n<!-- Generated by make docs-generate; do not edit by hand. -->\n\n" +
		"This is the protocol module's [minimal envelope](../../../livepeer-network-protocol/manifest/examples/minimal.json), validated with the registry boundary decoder. It is an illustrative fixture with a placeholder signature and historical timestamps, not a deployable signed publication. Its spec_version is fixture data, not the current daemon release version.\n\n" +
		"```json\n" + pretty.String() + "\n```\n\n" +
		"The signed wire shape is the outer manifest/signature envelope, not the resolver's node projection. The coordinator builds the payload, the cold console signs the entire canonical payload, and the coordinator hosts the signed result. See the [manifest contract](../product-specs/manifest-contract.md) for implemented checks and outstanding expiry/replay enforcement.\n")
	if check {
		existing, err := os.ReadFile(target)
		if err != nil {
			return err
		}
		if !bytes.Equal(existing, body) {
			return fmt.Errorf("%s is stale; run make docs-generate", target)
		}
		return nil
	}
	return os.WriteFile(target, body, 0644) //nolint:gosec // Generated public documentation must be readable by repository users.
}
